#!/usr/bin/env bash
# Runs one Codex task in its own git worktree and pushes branch codex/<id>.
#   agents/run-codex.sh <task-id> [extra instructions]
# The task brief is agents/tasks/<task-id>.md. The log goes to ~/codes/tk-logs/<task-id>.log.
set -uo pipefail
id="$1"; extra="${2:-}"
repo="$(cd "$(dirname "$0")/.." && pwd)"
wt="$HOME/codes/tk-wt/$id"; logs="$HOME/codes/tk-logs"; mkdir -p "$logs" "$(dirname "$wt")"
log="$logs/$id.log"; branch="codex/$id"
exec >>"$log" 2>&1
echo "=== $(date -Is) start $id"

git -C "$repo" fetch -q origin
if [ ! -d "$wt" ]; then
  if git -C "$repo" show-ref -q "refs/remotes/origin/$branch"; then
    git -C "$repo" worktree add -q -B "$branch" "$wt" "origin/$branch"
  else
    git -C "$repo" worktree add -q -B "$branch" "$wt" origin/main
  fi
fi
cd "$wt" || exit 1
git merge -q --no-edit origin/main || { echo "merge of main failed"; git merge --abort; }

prompt="You are Codex, a contributor to TrustChain Keyboard. Read AGENTS.md, then do task '$id' exactly as described in agents/tasks/$id.md. Work only in this folder (a git worktree on branch $branch); don't run git commit or push, since the runner does that. There is no network access in your sandbox, so skip any step that needs it and say so in agents/out/$id.md. $extra"
codex exec -s workspace-write -C "$wt" -o "$logs/$id.last.md" "$prompt" < /dev/null
rc=$?
echo "=== codex exit $rc"

git add -A
if ! git diff --cached --quiet; then
  git commit -q -m "codex: $id

Generated by Codex (run-codex.sh) from agents/tasks/$id.md"
fi
git push -q origin "$branch" && echo "=== pushed $branch $(git rev-parse --short HEAD)"
echo "=== $(date -Is) end $id"
